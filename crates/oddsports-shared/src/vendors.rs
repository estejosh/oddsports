//! Optional, config-driven sportsbook vendors.
//!
//! The repo hardcodes NO vendor. A deployment lists the vendors it works with
//! in a JSON file (`VENDORS_FILE`, or `vendors.json` inside `TEMPLATE_DIR`):
//!
//! ```json
//! [{"id": "example_a", "name": "Example Book A",
//!   "url": "https://example.com/go?sub={sub}", "commission": true}]
//! ```
//!
//! Rules enforced here, so no vendor can be privileged:
//!   * every vendor is neutral: there is no "affiliated" / related-party option,
//!     and a file that sets one (or any unknown field) is rejected;
//!   * every vendor is listed with equal prominence, alphabetically by name,
//!     regardless of file order;
//!   * links are https only, and `{sub}` (if present) is filled with an
//!     attribution tag (`surface_tier_game`), never a subscriber identifier;
//!   * if a vendor pays a commission, `commission: true` adds the notice. It is
//!     generated by code, so a template cannot drop it;
//!   * a bad file fails CLOSED (no vendors) rather than half-loading.
//!
//! No vendor ever appears next to odds; this block is a plain list of where
//! lines can be checked.

use serde::Deserialize;
use std::collections::BTreeSet;

const MAX_VENDORS: usize = 12;

#[derive(Debug, Clone, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Vendor {
    pub id: String,
    pub name: String,
    pub url: String,
    /// OddSports earns a commission on this vendor's links.
    #[serde(default)]
    pub commission: bool,
}

#[derive(Debug, Clone, Default)]
pub struct Vendors {
    list: Vec<Vendor>,
}

fn urlencode(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.' | '~') {
                c.to_string()
            } else {
                c.to_string().bytes().map(|b| format!("%{b:02X}")).collect()
            }
        })
        .collect()
}

impl Vendors {
    pub fn from_json(json: &str) -> Result<Self, String> {
        let mut list: Vec<Vendor> = serde_json::from_str(json).map_err(|e| format!("invalid vendors JSON: {e}"))?;
        if list.len() > MAX_VENDORS {
            return Err(format!("too many vendors (max {MAX_VENDORS})"));
        }
        let mut ids = BTreeSet::new();
        for v in &list {
            let id_ok = !v.id.is_empty()
                && v.id.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' || c == '-');
            if !id_ok {
                return Err(format!("vendor id {:?} must be lowercase [a-z0-9_-]", v.id));
            }
            if !ids.insert(v.id.clone()) {
                return Err(format!("duplicate vendor id {:?}", v.id));
            }
            let name = v.name.trim();
            if name.is_empty() || name.chars().count() > 60 || name.contains(['[', ']', '(', ')', '\n']) {
                return Err(format!("vendor {:?} has an invalid name", v.id));
            }
            if !v.url.starts_with("https://") || v.url.contains(char::is_whitespace) {
                return Err(format!("vendor {:?} url must be https with no whitespace", v.id));
            }
        }
        // Equal prominence: deterministic alphabetical order, never file order.
        list.sort_by_key(|v| v.name.trim().to_lowercase());
        Ok(Self { list })
    }

    pub fn from_file(path: &std::path::Path) -> Result<Self, String> {
        let s = std::fs::read_to_string(path).map_err(|e| format!("cannot read {}: {e}", path.display()))?;
        Self::from_json(&s)
    }

    pub fn is_empty(&self) -> bool {
        self.list.is_empty()
    }

    pub fn list(&self) -> &[Vendor] {
        &self.list
    }

    pub fn tracked_url(v: &Vendor, surface: &str, tier: &str, game_id: &str) -> String {
        let sub = urlencode(&format!("{surface}_{tier}_{game_id}"));
        v.url.replace("{sub}", &sub)
    }

    /// Disclosure text for the configured vendors, if any are configured.
    pub fn disclosure(&self) -> Option<String> {
        if self.list.is_empty() {
            return None;
        }
        let mut lines = Vec::new();
        if self.list.iter().any(|v| v.commission) {
            lines.push("Some links may earn OddSports a commission.");
        }
        lines.push("Vendors are listed alphabetically for reference only; no endorsement.");
        Some(lines.join(" "))
    }

    /// The vendor block appended (by code) to a pick. Empty string when no vendors.
    pub fn block(&self, surface: &str, tier: &str, game_id: &str) -> String {
        let Some(disclosure) = self.disclosure() else { return String::new() };
        let links: Vec<String> = self
            .list
            .iter()
            .map(|v| format!("[{}]({})", v.name.trim(), Self::tracked_url(v, surface, tier, game_id)))
            .collect();
        format!("\n\nSportsbooks: {}\n{}", links.join(" · "), disclosure)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const THREE: &str = r#"[
        {"id":"zeta","name":"Zeta Book","url":"https://z.example/go?sub={sub}","commission":true},
        {"id":"alpha","name":"Alpha Book","url":"https://a.example/go?sub={sub}"},
        {"id":"mid","name":"Mid Book","url":"https://m.example/go"}
    ]"#;

    #[test]
    fn empty_means_no_block_and_no_disclosure() {
        let v = Vendors::default();
        assert!(v.is_empty());
        assert_eq!(v.block("email", "Free", "g1"), "");
        assert!(v.disclosure().is_none());
    }

    #[test]
    fn listed_alphabetically_regardless_of_file_order() {
        let v = Vendors::from_json(THREE).unwrap();
        let names: Vec<_> = v.list().iter().map(|x| x.name.as_str()).collect();
        assert_eq!(names, ["Alpha Book", "Mid Book", "Zeta Book"]);
        let b = v.block("email", "Free", "g1");
        assert!(b.find("Alpha Book").unwrap() < b.find("Mid Book").unwrap());
        assert!(b.find("Mid Book").unwrap() < b.find("Zeta Book").unwrap());
    }

    #[test]
    fn commission_notice_comes_from_the_flag() {
        let b = Vendors::from_json(THREE).unwrap().block("email", "Free", "g1");
        assert!(b.contains("may earn OddSports a commission"));
        assert!(!b.to_lowercase().contains("affiliated"));
        assert!(b.contains("no endorsement"));
    }

    #[test]
    fn no_commission_flag_means_no_commission_notice() {
        let v = Vendors::from_json(r#"[{"id":"a","name":"A Book","url":"https://a.example/x"}]"#).unwrap();
        let d = v.disclosure().unwrap();
        assert!(!d.contains("commission"));
        assert!(d.contains("no endorsement"));
    }

    #[test]
    fn affiliated_or_unknown_fields_are_rejected() {
        let j = r#"[{"id":"a","name":"A","url":"https://a.example","affiliated":true}]"#;
        assert!(Vendors::from_json(j).is_err());
        let j2 = r#"[{"id":"a","name":"A","url":"https://a.example","featured":true}]"#;
        assert!(Vendors::from_json(j2).is_err());
    }

    #[test]
    fn sub_tag_is_filled_and_encoded_and_carries_no_subscriber_id() {
        let v = Vendors::from_json(THREE).unwrap();
        let b = v.block("email", "Analyst", "game 1/x");
        assert!(b.contains("sub=email_Analyst_game%201%2Fx"));
        assert!(!b.contains("{sub}"));
    }

    #[test]
    fn rejects_non_https_duplicates_bad_names_and_bad_ids() {
        let bad = |j: &str| Vendors::from_json(j).is_err();
        assert!(bad(r#"[{"id":"a","name":"A","url":"http://a.example"}]"#));
        assert!(bad(r#"[{"id":"a","name":"A","url":"https://a.example"},{"id":"a","name":"B","url":"https://b.example"}]"#));
        assert!(bad(r#"[{"id":"a","name":"A](https://evil)","url":"https://a.example"}]"#));
        assert!(bad(r#"[{"id":"A B","name":"A","url":"https://a.example"}]"#));
        assert!(bad(r#"[{"id":"a","name":"","url":"https://a.example"}]"#));
        assert!(bad(r#"[{"id":"a","name":"A","url":"https://a.example/ x"}]"#));
        assert!(bad("not json"));
    }

    #[test]
    fn caps_vendor_count() {
        let many: Vec<String> = (0..13)
            .map(|i| format!(r#"{{"id":"v{i}","name":"V {i}","url":"https://v{i}.example"}}"#))
            .collect();
        assert!(Vendors::from_json(&format!("[{}]", many.join(","))).is_err());
    }
}
